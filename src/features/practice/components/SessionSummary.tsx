import type { CoachSessionPlan, PracticeMode } from '../lib/types'

/** The end of a pass: the score, and for recall the coach's plan for next time. */
export default function SessionSummary({ mode, correctCount, attempts, plan }: {
  mode: PracticeMode
  correctCount: number
  attempts: number
  plan: { plan: CoachSessionPlan | null; loading: boolean; error: string }
}) {
  return (
    <>
      <p className="status success" style={{ marginTop: 0, marginBottom: '1.5rem' }}>
        Session complete. {correctCount} of {attempts} {mode === 'multiple-choice' ? 'questions were correct' : 'cards were sound'}.
      </p>
      {mode === 'recall' && (
        <div className="hint" style={{ marginTop: 0, marginBottom: '1.5rem' }}>
          <strong>Coach Session Plan</strong>
          {plan.loading && <p style={{ margin: '0.5rem 0 0' }}>Building your next-session plan...</p>}
          {plan.error && <p style={{ margin: '0.5rem 0 0' }}>{plan.error}</p>}
          {plan.plan && (
            <div style={{ marginTop: '0.6rem' }}>
              <p style={{ margin: '0.3rem 0' }}><strong>{plan.plan.headline}</strong></p>
              <p style={{ margin: '0.3rem 0' }}><strong>Focus:</strong> {plan.plan.focusTheme}</p>
              <p style={{ margin: '0.3rem 0' }}><strong>Warmup:</strong> {plan.plan.warmup}</p>
              <p style={{ margin: '0.3rem 0' }}><strong>Main Set:</strong> {plan.plan.mainSet}</p>
              <p style={{ margin: '0.3rem 0' }}><strong>Cooldown:</strong> {plan.plan.cooldown}</p>
              <p style={{ margin: '0.3rem 0' }}><strong>Note:</strong> {plan.plan.note}</p>
              <p style={{ margin: '0.3rem 0', opacity: 0.8 }}>Generated by {plan.plan.llmUsed ? 'LLM coach + rules' : 'rules coach'}.</p>
            </div>
          )}
        </div>
      )}
    </>
  )
}
